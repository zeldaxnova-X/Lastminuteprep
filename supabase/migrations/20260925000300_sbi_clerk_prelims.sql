-- SBI is its OWN entity: 5 options (A–E), 1/−0.25 marking, 3 sections, 20-min
-- sectional locks. Content is hard-isolated in the `sbi_clerk` schema (no shared
-- table with SSC). Shared answer columns are widened to A–E (backward-compatible
-- with SSC's A–D). Nothing SSC changes.
